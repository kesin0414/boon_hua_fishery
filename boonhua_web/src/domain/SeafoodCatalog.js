export function catalogSpeciesNames() {
  return SEAFOOD_CATALOG.map((entry) => entry.name);
}

export function findCatalogEntry(species) {
  const key = (species || '').trim().toLowerCase();
  return SEAFOOD_CATALOG.find((entry) => entry.name.toLowerCase() === key) || null;
}

export function filterCatalogNames(query) {
  const q = (query || '').trim().toLowerCase();
  if (!q) return catalogSpeciesNames();
  return SEAFOOD_CATALOG.filter(
    (entry) =>
      entry.name.toLowerCase().includes(q) ||
      entry.keywords.some((keyword) => keyword.includes(q) || q.includes(keyword)),
  ).map((entry) => entry.name);
}

export function allOcrHints() {
  const hints = new Set();
  for (const entry of SEAFOOD_CATALOG) {
    for (const keyword of entry.keywords) hints.add(keyword);
    entry.name
      .toLowerCase()
      .split(/[^a-z]+/)
      .filter((part) => part.length > 2)
      .forEach((part) => hints.add(part));
  }
  return [...hints];
}
